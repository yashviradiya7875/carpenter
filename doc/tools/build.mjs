const script = (lines) => ({ type: "text/javascript", exec: lines.split("\n") });

/**
 * Runs before every request. Signs in on its own when the request needs a
 * token and the stored one is missing or about to expire, using the
 * `username` / `password` variables — so any request works on a fresh import.
 */
const PRE_REQUEST = `// ── Auto-login ─────────────────────────────────────────────────────────
// Requests marked "No Auth" (public endpoints, login itself) skip this.
const auth = pm.request.auth;
const isPublic = auth && auth.type === "noauth";
if (!isPublic) {
    const token = pm.collectionVariables.get("authToken");
    const expiresAt = Number(pm.collectionVariables.get("authTokenExpiresAt") || 0);
    const fresh = token && Date.now() < expiresAt - 60 * 1000;
    const username = pm.variables.get("username");
    const password = pm.variables.get("password");

    if (!fresh && username && password) {
        pm.sendRequest({
            url: pm.variables.replaceIn("{{baseUrl}}") + "/api/login",
            method: "POST",
            header: { "Content-Type": "application/json" },
            body: { mode: "raw", raw: JSON.stringify({ data: { username: username, password: password } }) }
        }, function (err, res) {
            if (err) { console.error("Auto-login failed:", err); return; }
            let json = {};
            try { json = res.json(); } catch (e) { /* not JSON */ }
            if (json.result && json.result.token) {
                pm.collectionVariables.set("authToken", json.result.token);
                pm.collectionVariables.set("authTokenExpiresAt", String(jwtExpiry(json.result.token)));
                pm.collectionVariables.set("role", json.result.role || "");
                console.log("Auto-login OK as " + json.result.username);
            } else {
                console.warn("Auto-login refused:", (json.error && json.error.message) || res.status);
            }
        });
    } else if (!fresh) {
        console.warn("No token and no username/password set — set them in the environment or run Auth → login.");
    }
}

// Expiry of a JWT in epoch millis (0 when it can't be read → treated as expired).
function jwtExpiry(jwt) {
    try {
        let part = jwt.split(".")[1].replace(/-/g, "+").replace(/_/g, "/");
        while (part.length % 4) part += "=";
        return JSON.parse(atob(part)).exp * 1000;
    } catch (e) {
        return 0;
    }
}`;

/** Runs after every request: envelope check, drop a rejected token. */
const COLLECTION_TEST = `// ── Envelope check (all requests) ───────────────────────────────────────
let json = null;
try { json = pm.response.json(); } catch (e) { /* non-JSON (e.g. an HTML error page) */ }

pm.test("Responds with JSON", function () {
    pm.expect(json, "response body is not JSON").to.not.equal(null);
});

if (json && json.error) {
    console.warn(pm.info.requestName + " → " + json.error.status + ": " + json.error.message);
}

// A rejected token is dropped so the next request signs in again.
if (pm.response.code === 401 && pm.collectionVariables.get("authToken")) {
    pm.collectionVariables.set("authToken", "");
    pm.collectionVariables.set("authTokenExpiresAt", "0");
}`;

/** login's own test: store the JWT the collection's Bearer auth sends. */
const LOGIN_TEST = `// Store the token for every other request (Bearer {{authToken}}).
let body = null;
try { body = pm.response.json(); } catch (e) { /* not JSON */ }
pm.test("Login returned a token", function () {
    pm.expect(body && body.result && body.result.token, "no token in result").to.be.a("string");
});
if (body && body.result && body.result.token) {
    const token = body.result.token;
    let exp = 0;
    try {
        let part = token.split(".")[1].replace(/-/g, "+").replace(/_/g, "/");
        while (part.length % 4) part += "=";
        exp = JSON.parse(atob(part)).exp * 1000;
    } catch (e) { /* leave 0 → treated as expired */ }
    pm.collectionVariables.set("authToken", token);
    pm.collectionVariables.set("authTokenExpiresAt", String(exp));
    pm.collectionVariables.set("role", body.result.role || "");
    // Org chat room: the member's organization, or the organization itself.
    if (!pm.collectionVariables.get("organizationId")) {
        pm.collectionVariables.set("organizationId", body.result.organizationId || body.result.username);
    }
    console.log("Signed in as " + body.result.username + " (" + body.result.role + ")");
}`;

function captureScript(capture) {
  const lines = [
    "// Save ids from this response for the requests that follow.",
    "const get = (o, p) => p.split(\".\").reduce((a, k) => (a == null ? undefined : a[k]), o);",
    "let body = null;",
    "try { body = pm.response.json(); } catch (e) { /* not JSON */ }",
    "if (pm.response.code < 300 && body && body.result != null) {",
  ];
  for (const [variable, path] of Object.entries(capture)) {
    lines.push(`    const ${variable}Value = get(body.result, ${JSON.stringify(path)});`);
    lines.push(`    if (${variable}Value != null && ${variable}Value !== "") {`);
    lines.push(`        pm.collectionVariables.set(${JSON.stringify(variable)}, String(${variable}Value));`);
    lines.push(`        console.log("${variable} = " + ${variable}Value);`);
    lines.push("    }");
  }
  lines.push("}");
  return lines.join("\n");
}

function requestDescription(e) {
  const parts = [e.summary];
  parts.push(`\n**Auth:** ${AUTH_LABEL[e.auth]}`);
  if (e.required?.length) parts.push(`**Required:** ${e.required.map((r) => `\`${r}\``).join(", ")}`);
  if (e.returns) parts.push(`**Returns:** ${e.returns}`);
  if (e.notes) parts.push(`**Notes:** ${e.notes}`);
  if (e.capture) {
    parts.push(`**Saves:** ${Object.keys(e.capture).map((k) => `\`{{${k}}}\``).join(", ")}`);
  }
  return parts.join("\n\n");
}

function buildItem(e) {
  const path = pathOf(e).replace(/^\//, "").split("/");
  const request = {
    method: methodOf(e),
    header: [],
    url: { raw: `{{baseUrl}}${pathOf(e)}`, host: ["{{baseUrl}}"], path },
    description: requestDescription(e),
  };
  if (e.auth === "public") request.auth = { type: "noauth" };

  if (e.multipart) {
    request.body = {
      mode: "formdata",
      formdata: e.form.map((f) =>
        f.type === "file"
          ? { key: f.key, type: "file", src: [], description: f.description }
          : { key: f.key, value: f.value, type: "text", description: f.description, ...(f.disabled ? { disabled: true } : {}) },
      ),
    };
  } else if (methodOf(e) === "POST") {
    request.header.push({ key: "Content-Type", value: "application/json" });
    request.body = {
      mode: "raw",
      raw: JSON.stringify({ data: e.body ?? {} }, null, 2),
      options: { raw: { language: "json" } },
    };
  }

  const item = { name: e.name, request, response: [] };
  if (e.name === "login") item.event = [{ listen: "test", script: script(LOGIN_TEST) }];
  else if (e.capture) item.event = [{ listen: "test", script: script(captureScript(e.capture)) }];
  return item;
}

